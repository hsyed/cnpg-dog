#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# Read both pins from the devShell; never select "latest".
image=${KIND_NODE_IMAGE:?}
version=${image#*:}
version=${version%%@*}
kubernetes_url="https://raw.githubusercontent.com/kubernetes/kubernetes/$version/api/openapi-spec/swagger.json"
cnpg_url=${CNPG_MANIFEST:?}
curl -fsSL "$kubernetes_url" > "$tmp/kubernetes.json"
curl -fsSL "$cnpg_url" > "$tmp/cnpg.yaml"

# Keep the native definitions we consume and their transitive references.
# Swagger's int-or-string format needs an explicit JSON Schema union.
jq '
  .definitions as $defs |
  {
    Namespace: "io.k8s.api.core.v1.Namespace",
    ConfigMap: "io.k8s.api.core.v1.ConfigMap",
    Secret: "io.k8s.api.core.v1.Secret",
    Service: "io.k8s.api.core.v1.Service",
    Deployment: "io.k8s.api.apps.v1.Deployment",
    ResourceRequirements: "io.k8s.api.core.v1.ResourceRequirements",
    Affinity: "io.k8s.api.core.v1.Affinity",
    TopologySpreadConstraint: "io.k8s.api.core.v1.TopologySpreadConstraint"
  } as $aliases |
  def expand:
    (. + [.[] as $name | $defs[$name] | .. | objects |
      ."$ref"? // empty | select(startswith("#/definitions/")) |
      ltrimstr("#/definitions/")]) | unique;
  ($aliases | [.[]] | unique | until(. == expand; expand)) as $names |
  {
    "$schema": "http://json-schema.org/draft-04/schema#",
    type: "object",
    definitions:
      (($defs | with_entries(select(.key as $key | $names | index($key)))) +
       ($aliases | with_entries(.value = {"$ref": ("#/definitions/" + .value)})))
  } |
  walk(if type == "object" then
    del(.description) |
    if .type? == "object" and has("properties") and
      (has("additionalProperties") | not) and
      .["x-kubernetes-preserve-unknown-fields"]? != true
    then .additionalProperties = false else . end |
    if .format? == "int-or-string" then
      .type = ["integer", "string"] | del(.format)
    else . end
  else . end)
' "$tmp/kubernetes.json" > "$tmp/kubernetes-schema.json"

yq -o=json -I=0 '
  select(.kind == "CustomResourceDefinition" and .metadata.name == "clusters.postgresql.cnpg.io") |
  .spec.versions[] | select(.name == "v1") | .schema.openAPIV3Schema
' "$tmp/cnpg.yaml" | jq -e '
  select(.properties.spec.properties.storage != null) |
  {
    "$schema": "http://json-schema.org/draft-04/schema#",
    type: "object",
    definitions: {
      Cluster: .,
      StorageConfiguration: .properties.spec.properties.storage,
      AffinityConfiguration: .properties.spec.properties.affinity
    }
  } |
  walk(if type == "object" then
    del(.description) |
    if .type? == "object" and has("properties") and
      (has("additionalProperties") | not) and
      .["x-kubernetes-preserve-unknown-fields"]? != true
    then .additionalProperties = false else . end
  else . end)
' > "$tmp/cnpg-schema.json"

mkdir -p lib/schema/upstream
for source in kubernetes cnpg; do
  cue import jsonschema -p upstream -o "$tmp/$source.cue" "$tmp/$source-schema.json"
  if [ "$source" = kubernetes ]; then url=$kubernetes_url; else url=$cnpg_url; fi
  {
    printf '// Code generated by scripts/update-schemas.sh; DO NOT EDIT.\n'
    printf '// Source: %s\n\n' "$url"
    cat "$tmp/$source.cue"
  } > "lib/schema/upstream/${source}_gen.cue"
done
cue fmt ./lib/schema/upstream
echo "Updated Kubernetes $version and pinned CNPG schemas"
